/// Provinces whose name contains [query] (trimmed); all of them when empty.
List<String> searchThaiProvinces(String query) {
  final q = query.trim();
  if (q.isEmpty) return kThaiProvinces;
  return kThaiProvinces.where((p) => p.contains(q)).toList();
}
